import { type Metadata } from 'next';
import { type SiteContent } from '@/content/types';
import {
  alternatePaths,
  hreflangPaths,
  htmlLang,
  type Locale,
  localePath,
  locales,
  ogLocale,
  type RouteKey,
} from './i18n';
import { site } from './site';

interface PageMeta {
  locale: Locale;
  content: SiteContent;
  title?: string;
  description?: string;
  key?: RouteKey;
  slug?: string;
  noIndex?: boolean;
}

export function buildMetadata({
  locale,
  content,
  title,
  description,
  key,
  slug,
  noIndex = false,
}: PageMeta): Metadata {
  const paths = alternatePaths(key, slug);
  const canonical = paths[locale];
  const desc = description ?? content.meta.description;
  // Nested pages set their own `openGraph`, which drops the image generated by
  // `app/[locale]/opengraph-image.tsx`; point every page at it explicitly.
  const images = [
    { url: `/${locale}/opengraph-image`, width: 1200, height: 630, alt: content.meta.ogAlt },
  ];

  return {
    metadataBase: new URL(site.url),
    title: title ? { absolute: `${title} — ${site.name}` } : { absolute: content.meta.title },
    description: desc,
    keywords: content.meta.keywords,
    authors: [{ name: site.name, url: site.url }],
    creator: site.name,
    publisher: site.name,
    applicationName: site.name,
    alternates: {
      canonical,
      languages: hreflangPaths(key, slug),
    },
    openGraph: {
      type: 'website',
      siteName: site.name,
      locale: ogLocale[locale],
      alternateLocale: locales.filter((other) => other !== locale).map((other) => ogLocale[other]),
      url: canonical,
      title: title ? `${title} — ${site.name}` : content.meta.title,
      description: desc,
      images,
    },
    twitter: {
      card: 'summary_large_image',
      title: title ? `${title} — ${site.name}` : content.meta.title,
      description: desc,
      images,
    },
    robots: noIndex
      ? { index: false, follow: false }
      : {
          index: true,
          follow: true,
          googleBot: {
            index: true,
            follow: true,
            'max-image-preview': 'large',
            'max-snippet': -1,
            'max-video-preview': -1,
          },
        },
    formatDetection: { telephone: false, email: false, address: false },
  };
}

const absolute = (path: string) => `${site.url}${path}`;

export function organizationJsonLd(locale: Locale, content: SiteContent) {
  return {
    '@context': 'https://schema.org',
    // ProfessionalService is a LocalBusiness, itself an Organization: local search signals
    // (address, area served) without losing the organization semantics.
    '@type': 'ProfessionalService',
    '@id': `${site.url}/#organization`,
    name: site.name,
    url: absolute(localePath(locale)),
    logo: absolute(site.logo),
    email: site.email,
    foundingDate: String(site.foundingYear),
    description: content.meta.description,
    sameAs: [site.linkedin],
    address: {
      '@type': 'PostalAddress',
      streetAddress: site.address.street,
      postalCode: site.address.postalCode,
      addressLocality: site.address.city,
      addressCountry: site.country,
    },
    vatID: site.vatId,
    identifier: site.companyNumber,
    areaServed: [
      { '@type': 'Country', name: 'Belgium' },
      { '@type': 'City', name: 'Charleroi' },
      { '@type': 'AdministrativeArea', name: 'Wallonie' },
      { '@type': 'AdministrativeArea', name: 'Bruxelles-Capitale' },
    ],
    knowsLanguage: ['fr', 'en', 'nl'],
    image: absolute(site.logo),
    contactPoint: {
      '@type': 'ContactPoint',
      contactType: 'sales',
      email: site.email,
      availableLanguage: ['French', 'English', 'Dutch'],
    },
  };
}

export function websiteJsonLd(locale: Locale, content: SiteContent) {
  return {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    '@id': `${site.url}/#website`,
    url: absolute(localePath(locale)),
    name: site.name,
    description: content.meta.description,
    inLanguage: htmlLang[locale],
    publisher: { '@id': `${site.url}/#organization` },
  };
}

export function servicesJsonLd(locale: Locale, content: SiteContent) {
  return {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    itemListElement: content.expertises.offers.map((offer, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      item: {
        '@type': 'Service',
        name: offer.title,
        description: offer.solution,
        provider: { '@id': `${site.url}/#organization` },
        areaServed: { '@type': 'Country', name: 'Belgium' },
        url: absolute(localePath(locale, 'services', offer.slug)),
      },
    })),
  };
}

/** One offer's own page, as Service structured data. */
export function serviceJsonLd(locale: Locale, content: SiteContent, slug: string) {
  const offer = content.expertises.offers.find((item) => item.slug === slug);
  if (!offer) return null;
  return {
    '@context': 'https://schema.org',
    '@type': 'Service',
    name: offer.title,
    description: offer.solution,
    provider: { '@id': `${site.url}/#organization` },
    areaServed: { '@type': 'Country', name: 'Belgium' },
    url: absolute(localePath(locale, 'services', offer.slug)),
  };
}

/** The home page FAQ, as FAQPage structured data (same text as the visible answers). */
export function faqJsonLd(content: SiteContent) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: content.faq.items.map((item) => ({
      '@type': 'Question',
      name: item.question,
      acceptedAnswer: { '@type': 'Answer', text: item.answer },
    })),
  };
}

export function breadcrumbJsonLd(items: { name: string; path: string }[]) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map((item, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: item.name,
      item: absolute(item.path),
    })),
  };
}

export function caseStudyJsonLd(
  locale: Locale,
  title: string,
  description: string,
  path: string,
  image: string,
) {
  return {
    '@context': 'https://schema.org',
    '@type': 'CreativeWork',
    name: title,
    description,
    url: absolute(path),
    image: absolute(image),
    inLanguage: htmlLang[locale],
    author: { '@id': `${site.url}/#organization` },
  };
}
